export function normalizeLang(value) {
  const lang = String(value || '').trim().toLowerCase().slice(0, 2);
  return SUPPORTED_LANGS.has(lang) ? lang : '';
}

export function getCopy(lang) {
  return COPY[normalizeLang(lang) || 'ko'];
}
